import puppeteer from "puppeteer-core"
const browser = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: true, args: ["--no-sandbox","--disable-gpu"], defaultViewport: { width: 1440, height: 1000 } })
const page = await browser.newPage()
await page.goto("http://127.0.0.1:5199/articles/beihai9-replay-demo", { waitUntil: "domcontentloaded" })
await new Promise(r => setTimeout(r, 4000))
await page.evaluate(() => document.querySelector(".replay-block__poster")?.click())
await new Promise(r => setTimeout(r, 800))
await page.evaluate(() => { document.querySelector("trpg-replay").seek(151) })
await new Promise(r => setTimeout(r, 7000))
await page.evaluate(() => { const el = document.querySelector(".replay-block"); window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - 140, behavior: "instant" }) })
await new Promise(r => setTimeout(r, 500))
await page.screenshot({ path: ".tmp/real-characters.png" })
await page.evaluate(() => { document.querySelector("trpg-replay").seek(230) })
await new Promise(r => setTimeout(r, 8000))
await page.screenshot({ path: ".tmp/real-montage.png" })
console.log("ok")
await browser.close()
